void test_rotate() {
  int t[] = {I, J, L, O, S, T, Z};

  for (int i = 0; i < 7; i++) {
    Matrix M = block_get_shape(t[i]);
    matrix_rotate_right(M);
    matrix_rotate_left(M);
  }

  assert_bool(true, "rotate all blocks");
}

void test_rotate_block() {
  // make sure everyblock is rotatable

  Block b_T = {.color = 1,
               .type = T,
               .position = {.x = 1, .y = 1},
               .shape = block_get_shape(T)};

  Matrix left = matrix_rotate_left(b_T.shape);

  int expected_left[] = {
      // clang-format off
        0, 1, 0,
        1, 1, 0,
        0, 1, 0
      // clang-format on
  };

  assert_res(
      matrix_compare(left, matrix_from(3, 3, expected_left), "rotate left"));

  Matrix right = matrix_rotate_right(b_T.shape);
  int expected_right[] = {
      // clang-format off
        0, 1, 0,
        0, 1, 1,
        0, 1, 0
      // clang-format on
  };

  assert_res(
      matrix_compare(right, matrix_from(3, 3, expected_right), "rotate right"));
}

